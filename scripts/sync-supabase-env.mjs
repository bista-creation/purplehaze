/**
 * Copies only the local Supabase values the app needs into .env.local.
 * The service-role key is intentionally never read or written.
 *
 * Usage: npm run db:local:env (after `npm run db:local:start`)
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();
const envLocalPath = resolve(root, ".env.local");

let raw;
try {
  const command = process.platform === "win32" ? "npx.cmd" : "npx";
  raw = execFileSync(command, ["supabase", "status", "-o", "env"], {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  });
} catch {
  console.error(
    "Could not read local Supabase status. Start Docker Desktop, then run `npm run db:local:start`.",
  );
  process.exit(1);
}

const values = new Map();
for (const line of raw.split(/\r?\n/)) {
  const match = line.match(/^([A-Z0-9_]+)=(?:"(.*)"|(.*))$/);
  if (!match) continue;
  values.set(match[1], match[2] ?? match[3] ?? "");
}

const apiUrl = values.get("API_URL") ?? "http://127.0.0.1:54321";
const anonKey = values.get("ANON_KEY");
const jwtSecret = values.get("JWT_SECRET");
const dbUrl =
  values.get("DB_URL") ??
  "postgresql://postgres:postgres@127.0.0.1:54322/postgres";

if (!anonKey || !jwtSecret) {
  console.error(
    "Local Supabase status did not include ANON_KEY and JWT_SECRET. Is the stack running?",
  );
  process.exit(1);
}

const existing = existsSync(envLocalPath)
  ? readFileSync(envLocalPath, "utf8")
  : "";
const lines = existing ? existing.split(/\r?\n/) : [];
const updates = new Map([
  ["DATABASE_URL", `"${dbUrl}"`],
  ["DIRECT_URL", `"${dbUrl}"`],
  ["NEXT_PUBLIC_SUPABASE_URL", `"${apiUrl}"`],
  ["NEXT_PUBLIC_SUPABASE_ANON_KEY", `"${anonKey}"`],
  ["SUPABASE_JWT_SECRET", `"${jwtSecret}"`],
]);

const seen = new Set();
const output = [];
for (const line of lines) {
  const match = line.match(/^([A-Z0-9_]+)=/);
  if (match && updates.has(match[1])) {
    output.push(`${match[1]}=${updates.get(match[1])}`);
    seen.add(match[1]);
  } else {
    output.push(line);
  }
}
if (!existing) {
  output.push(
    "# Generated by scripts/sync-supabase-env.mjs. Never commit this file.",
  );
}
for (const [key, value] of updates) {
  if (!seen.has(key)) output.push(`${key}=${value}`);
}
writeFileSync(
  envLocalPath,
  `${output.join("\n").replace(/\n*$/, "\n")}`,
  "utf8",
);
console.log(
  "Wrote local Supabase database, anon, and JWT values to .env.local (untracked).",
);
